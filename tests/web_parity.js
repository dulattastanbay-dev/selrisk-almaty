const fs=require("fs"),path=require("path");
const root=path.join(__dirname,".."),kind=process.argv[2]||"power";
const {score,validateScenario,season}=require(path.join(root,"web/model.js"));
const model=JSON.parse(fs.readFileSync(path.join(root,`web/data/model_${kind}.json`)));
const packed=JSON.parse(fs.readFileSync(path.join(root,`web/data/archive_${kind}.json`)));
const rows=packed.data.map(values=>Object.fromEntries(packed.columns.map((key,i)=>[key,values[i]])));
const assert=require("assert");
assert.throws(()=>season("2020-02-31"));
assert.equal(score(model,{}).score,null);
let row=rows.find(r=>score(model,r).score!==null);
assert.equal(validateScenario(model,row).status,"available");
let bad={...row,[model.features[0]]:-1};
assert.throws(()=>validateScenario(model,bad));
bad={...row,[model.features[0]]:null};assert.equal(score(model,bad).score,null);
bad={...row,[model.features[0]]:1e9};assert.equal(score(model,bad).status,"out_of_training_domain");
console.log(JSON.stringify(rows.map(row=>score(model,row))));
